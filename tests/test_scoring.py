def test_duplicate_sort_pinned_case():
    """test.sh:123-126."""
    assert sort_duplicate_codes("10.001,2.002,2.001") == "2.001,2.002,10.001"


def test_duplicate_sort_needs_both_guards():
    """B5: only a comma-bearing, purely numeric field is reordered."""
    assert sort_duplicate_codes("~5,6") == "~5,6"
    assert sort_duplicate_codes("5?,6") == "5?,6"
    assert sort_duplicate_codes("6,5") == "5,6"
    assert sort_duplicate_codes("16") == "16"
    assert sort_duplicate_codes("-") == "-"
    assert sort_duplicate_codes("1,1") == "1,1"


def test_duplicate_sort_survives_a_malformed_field():
    """Unreachable with the shipped DB, but it must not raise."""
    assert sort_duplicate_codes("1,,2") == "1,,2"
    assert sort_duplicate_codes("1,2.3.4") == "1,2.3.4"


def test_duplicate_sort_is_stable():
    assert sort_duplicate_codes("2,1,2") == "1,2,2"


