def test_status_order_is_the_specification():
    assert status_column("184", 100, ["16", "1"]) == "PERFECT"
    assert status_column("-", 0, []) == "NONE"
    assert status_column("-", 90, ["7", "1", "1"]) == "NOVEL"
    assert status_column("-", 90, ["7", "1,1"]) == "MIXED"
    assert status_column("-", 51, ["~66", "-"]) == "MISSING"
    assert status_column("-", 60, ["~66", "~1"]) == "BAD"
    assert status_column("-", 74, ["~66", "20"]) == "OK"


def test_perfect_wins_over_everything_even_with_null_codes():
    """A rewritten null still reports PERFECT (5.15, B3)."""
    assert status_column("64", 100, ["10", "0", "15"]) == "PERFECT"


def test_decimal_st_is_not_perfect():
    assert status_column("206.2", 100, ["1"]) != "PERFECT"


def test_missing_tests_containment_not_equality():
    """MISSING fires on a code that CONTAINS '-', not one that equals it."""
    assert status_column("-", 80, ["1-2"]) == "MISSING"


def test_none_beats_novel_when_score_is_zero():
    assert status_column("-", 0, ["1", "2"]) == "NONE"


