"""Scoring, status and duplicate-code tests. docs/ARCHITECTURE.md 5.9, 5.15.

The centrepiece is :func:`test_all_986_tuples`, which asserts every row of
``tests/golden/scores.tsv`` -- a table generated by running the REAL Perl
``mlst`` arithmetic. 79 of its 986 rows disagree with exact-rational maths
because Perl uses IEEE-754 doubles, so a Decimal/Fraction implementation
fails here and nowhere else.

Runnable as ``python3 -m pytest tests/test_scoring.py`` or ``python3
tests/test_scoring.py``.
"""

from __future__ import annotations

import os
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from wmlst.engine import (
    classify,
    score_signature,
    sort_duplicate_codes,
    status_column,
)

HERE = os.path.dirname(os.path.abspath(__file__))
SCORES_TSV = os.path.join(HERE, "golden", "scores.tsv")


def _signature(nlocii: int, n_tilde: int, n_question: int, n_dash: int) -> str:
    """A signature carrying exactly the requested marker counts.

    The scoring function counts characters, so the filler codes must contain
    none of ``~``, ``?`` or ``-``.
    """
    n_plain = nlocii - n_tilde - n_question - n_dash
    assert n_plain >= 0
    fields = (["~1"] * n_tilde + ["1?"] * n_question + ["-"] * n_dash
              + ["1"] * n_plain)
    return "/".join(fields)


def _load_scores():
    rows = []
    with open(SCORES_TSV, encoding="utf-8", newline=None) as fh:
        header = fh.readline().split()
        assert header == ["nlocii", "n_tilde", "n_question", "n_dash",
                          "score"], header
        for line in fh:
            line = line.strip()
            if not line:
                continue
            nlocii, n_tilde, n_question, n_dash, score = (
                int(x) for x in line.split())
            rows.append((nlocii, n_tilde, n_question, n_dash, score))
    return rows


def test_scores_tsv_is_the_expected_table():
    """The golden table must be present and complete (986 tuples, 3..10 loci)."""
    rows = _load_scores()
    assert len(rows) == 986
    assert {r[0] for r in rows} == set(range(3, 11))


def test_all_986_tuples():
    """Section 5.9 step 43: every Perl-generated tuple, exactly.

    Acceptance-checklist item 3. The ``st`` argument is ``'-'`` because the
    reference table records the pre-``+10`` score.
    """
    failures = []
    for nlocii, n_tilde, n_question, n_dash, expected in _load_scores():
        sig = _signature(nlocii, n_tilde, n_question, n_dash)
        got = score_signature(sig, nlocii, "-")
        if got != expected:
            failures.append((nlocii, n_tilde, n_question, n_dash, expected, got))
    assert not failures, "%d of 986 tuples wrong, first: %r" % (
        len(failures), failures[:5])


def test_ieee754_really_is_required():
    """At least one golden row must disagree with exact-rational arithmetic.

    If this ever stops finding disagreements the golden table has been
    regenerated from something other than Perl, and the float mandate in
    section 5.9 step 43 has quietly lost its teeth.
    """
    divergent = 0
    for nlocii, n_tilde, n_question, n_dash, expected in _load_scores():
        exact = (Fraction(nlocii)
                 - Fraction(3, 10) * n_tilde
                 - Fraction(1, 2) * n_question
                 - Fraction(1) * n_dash) * 90 / nlocii
        if int(exact) != expected:
            divergent += 1
    assert divergent == 79, divergent


def test_multiplication_order_is_not_reassociable():
    """``int(s*90/n)`` != ``int(s*(90/n))`` for the pinned shapes (5.9 step 43)."""
    # n=7, three '~', one '?'
    sig = _signature(7, 3, 1, 0)
    assert score_signature(sig, 7, "-") == 71
    s = 7.0 - 0.3 * 3 - 0.5 * 1
    assert int(s * (90 / 7)) == 72          # the WRONG reassociation
    # n=9, one '~'
    assert score_signature(_signature(9, 1, 0, 0), 9, "-") == 86
    s = 9.0 - 0.3
    assert int(s * (90 / 9)) == 87          # the WRONG reassociation


def test_int_truncates_toward_zero_not_floor():
    """Section 5.9 step 43: ``//`` is wrong for a negative intermediate."""
    # A 7-locus scheme with 7 '?' and 4 '-' cannot happen, but the arithmetic
    # must still truncate: int(-0.5*90/7) == -6 while (-0.5*90/7)//1 == -7.0.
    value = -0.5 * 90 / 7
    assert int(value) == -6
    assert value // 1 == -7.0


def test_st_bonus_is_exactly_ten():
    assert score_signature(_signature(7, 0, 0, 0), 7, "-") == 90
    assert score_signature(_signature(7, 0, 0, 0), 7, "184") == 100


def test_seven_locus_reference_anchors():
    """The regression anchors quoted in section 5.9."""
    anchors = {
        (0, 0, 0): (90, 100),
        (1, 0, 0): (86, 96),
        (0, 1, 0): (83, 93),
        (0, 0, 1): (77, 87),
        (0, 0, 2): (64, 74),
        (0, 0, 3): (51, 61),
        (0, 0, 4): (38, 48),
    }
    for (t, q, d), (no_st, with_st) in anchors.items():
        sig = _signature(7, t, q, d)
        assert score_signature(sig, 7, "-") == no_st, (t, q, d)
        assert score_signature(sig, 7, "1") == with_st, (t, q, d)


def test_aphagocytophilum_can_never_reach_100():
    """Section 5.19a: 8 header genes, 7 .tfa files, so one field is always '-'."""
    sig = _signature(8, 0, 0, 1)
    assert score_signature(sig, 8, "-") == 78
    assert score_signature(sig, 8, "12") == 88


def test_halobacteria_and_mhominis_ceilings():
    """Section 5.19b: the uncallable loci cap these two schemes."""
    assert score_signature(_signature(5, 0, 0, 2), 5, "-") == 54
    assert score_signature(_signature(10, 0, 0, 1), 10, "-") == 81


