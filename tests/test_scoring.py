def test_classify_order():
    assert classify("-") == "missing"
    assert classify("0") == "null"
    assert classify("1,2") == "multiple"
    assert classify("~16") == "novel"
    assert classify("16?") == "partial"
    assert classify("16") == "exact"
    assert classify("2.002") == "exact"


def test_classify_null_is_tested_before_the_numeric_case():
    """'0' is the /- -> /0 rewrite, never an allele named zero (3.2.1)."""
    assert classify("0") == "null"
    assert classify("00") == "exact"


